"""Export scikit-learn Random Forests to ONNX and check that both give the same answers.

ONNX is a portable, non-executable model format: a small runtime (onnxruntime) can run it on a
Raspberry Pi-class device without scikit-learn or Python pickles.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import numpy as np

from pdm.config import PROJECT_ROOT, load_config, path


def to_onnx(model, n_features: int, out: Path) -> Path:
    from skl2onnx import to_onnx as _to_onnx

    X0 = np.zeros((1, n_features), dtype=np.float32)
    # zipmap=False -> probabilities come out as a plain (n, n_classes) float array
    onx = _to_onnx(model, X0, options={id(model): {"zipmap": False}}, target_opset=17)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(onx.SerializeToString())
    return out


def onnx_session(onnx_path: Path):
    import onnxruntime as ort

    so = ort.SessionOptions()
    so.intra_op_num_threads = 1  # behave like a small single-core edge device
    return ort.InferenceSession(str(onnx_path), sess_options=so, providers=["CPUExecutionProvider"])


def onnx_predict(sess, X: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Returns (labels, probabilities)."""
    name = sess.get_inputs()[0].name
    labels, proba = sess.run(None, {name: np.asarray(X, dtype=np.float32)})
    return np.asarray(labels), np.asarray(proba)


def parity_check(model, sess, X: np.ndarray) -> dict:
    """Compare scikit-learn and ONNX on the same inputs.

    ONNX runs in float32 while scikit-learn uses float64, so a window whose feature value sits
    exactly on a tree threshold can (rarely) fall on the other side. We report how often that happens.
    """
    sk_proba = model.predict_proba(X)
    sk_label = model.classes_[sk_proba.argmax(axis=1)]
    ox_label, ox_proba = onnx_predict(sess, X)
    return {
        "n": int(len(X)),
        "label_agreement": float(np.mean(sk_label.astype(str) == ox_label.astype(str))),
        "label_mismatches": int(np.sum(sk_label.astype(str) != ox_label.astype(str))),
        "max_abs_prob_diff": float(np.max(np.abs(sk_proba - ox_proba))),
    }


def write_edge_bundle(model_files: dict[str, Path], feature_cols: list[str], severity_cols: list[str],
                      classes: dict[str, list[str]]) -> Path:
    """Copy everything edge/edge_infer.py needs into edge/: ONNX models, the feature code and a JSON
    config. The bundle needs only numpy + scipy + onnxruntime."""
    from pdm.signal.features import feature_names, params_from_config

    edge_dir = PROJECT_ROOT / "edge"
    edge_dir.mkdir(exist_ok=True)
    for name, src in model_files.items():
        shutil.copy2(src, edge_dir / f"{name}.onnx")
    shutil.copy2(PROJECT_ROOT / "pdm" / "signal" / "features.py", edge_dir / "edge_features.py")
    cfg = load_config()
    edge_cfg = {
        "target_fs": cfg["data"]["target_fs"], "window_size": cfg["signal"]["window_size"],
        "overlap": cfg["signal"]["overlap"], "feature_params": params_from_config(),
        "feature_cols": feature_cols, "severity_cols": severity_cols, "all_feature_names": feature_names(params_from_config()),
        "physics": cfg["physics"], "classes": classes,
        "models": {k: f"{k}.onnx" for k in model_files},
        "note": "Generated by scripts/04_edge_benchmark.py - do not edit by hand.",
    }
    (edge_dir / "edge_config.json").write_text(json.dumps(edge_cfg, indent=2), encoding="utf-8")
    return edge_dir


def models_dir() -> Path:
    return path("models_dir")
